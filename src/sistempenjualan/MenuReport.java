    private void export_stokActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_export_stokActionPerformed
        // TODO add your handling code here:
        try {
            this.dateValidation();
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

            String start_dates = sdf.format(start_date.getDate());
            String end_dates = sdf.format(end_date.getDate());

            HashMap<String, Object> parameter = new HashMap<>();

            parameter.put("start", start_dates);
            parameter.put("end", end_dates);

            JasperPrint jp = JasperFillManager.fillReport(
                    getClass().getResourceAsStream("/sistempenjualan/reports/report_stock.jasper"),
                    parameter,
                    Koneksi.con
            );

            JasperViewer.viewReport(jp, false);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Peringatan", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_export_stokActionPerformed

