    private void export_transaksiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_export_transaksiActionPerformed
        // TODO add your handling code here:
        Locale locale = new Locale("id", "ID");
        Locale.setDefault(locale);
        Connection koneksi;
        try {
            koneksi = Koneksi.getConnection();
            File file = new File("src/sistempenjualan/reports/report_penjualan.jrxml");
            JasperDesign jasperDesign = JRXmlLoader.load(file);
            JasperReport jasperReport = JasperCompileManager.compileReport(jasperDesign);

            Map<String, Object> param = new HashMap<>();
            param.put("start_date", start.getDate());
            param.put("end_date", end.getDate());
            Integer salesId = salesMap.get((String) jComboBox1.getSelectedItem());
            param.put("sales_id", salesId);

            JasperPrint jasperPrint = JasperFillManager.fillReport(jasperReport, param, koneksi);
            JasperViewer.viewReport(jasperPrint, false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
            e.printStackTrace();
        }
    }//GEN-LAST:event_export_transaksiActionPerformed

