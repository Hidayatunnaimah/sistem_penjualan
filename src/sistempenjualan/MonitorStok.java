    private void loadCardData() {
        try {
            String query = "SELECT " +
                "SUM(CASE WHEN stock <= 0 THEN 1 ELSE 0 END) AS habis, " +
                "SUM(CASE WHEN stock > 0 AND stock <= min_stock THEN 1 ELSE 0 END) AS menipis, " +
                "SUM(CASE WHEN stock > min_stock THEN 1 ELSE 0 END) AS tersedia " +
                "FROM stock";

            rs = Koneksi.stm.executeQuery(query);

            if (rs.next()) {
                tersedia.setText(String.valueOf(rs.getInt("tersedia")));
                menipis.setText(String.valueOf(rs.getInt("menipis")));
                habis.setText(String.valueOf(rs.getInt("habis")));
            }

            rs.close();
        } catch (Exception e) {
            System.err.println("Error loadCardData: " + e.getMessage());
        }
    }

    private void loadTableData() {
        try {
            String query =
                "SELECT mp.code, mp.product_name, s.stock, mv.vendor_name " +
                "FROM stock s " +
                "LEFT JOIN m_product mp ON mp.id = s.product_id " +
                "LEFT JOIN m_vendor mv ON mv.id = mp.vendor_id " +
                "ORDER BY s.stock ASC";

            rs = Koneksi.stm.executeQuery(query);

            String[] columns = {"Kode", "Nama Produk", "Stok", "Vendor"};
            DefaultTableModel model = new DefaultTableModel(columns, 0);
            monitorstok_table.getTableHeader().setFont(
                new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 30)
            );

            monitorstok_table.getTableHeader().setPreferredSize(
                new java.awt.Dimension(0, 40)
            );
            
            DefaultTableCellRenderer centerRenderer = (DefaultTableCellRenderer)
            monitorstok_table.getTableHeader().getDefaultRenderer();
            centerRenderer.setHorizontalAlignment(JLabel.CENTER);

            while (rs.next()) {
                Object[] row = {
                    rs.getString("code"),
                    rs.getString("product_name"),
                    rs.getInt("stock"),
                    rs.getString("vendor_name")
                };
                model.addRow(row);
            }

            monitorstok_table.setModel(model);
            rs.close();
        } catch (Exception e) {
            System.err.println("Error loadTableData: " + e.getMessage());
        }
    }

