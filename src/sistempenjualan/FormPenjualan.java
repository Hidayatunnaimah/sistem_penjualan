    private void generateNoTransaksi() {
        try {
            String today = new SimpleDateFormat("yyyyMMdd").format(new Date());
            String query = "SELECT MAX(CAST(SUBSTRING(trx_number, 14) AS UNSIGNED)) AS max_no "
                    + "FROM trx WHERE trx_number LIKE 'TRX-" + today + "-%'";
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(query);

            int nextNo = 1;
            if (rs.next() && rs.getInt("max_no") > 0) {
                nextNo = rs.getInt("max_no") + 1;
            }
            jTextField1.setText(String.format("TRX-%s-%03d", today, nextNo));
        } catch (SQLException e) {
            String today = new SimpleDateFormat("yyyyMMdd").format(new Date());
            jTextField1.setText("TRX-" + today + "-001");
        }
    }

