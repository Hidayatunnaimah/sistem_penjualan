    private void tambahCustomerBaru() {
        String nama = jTextField4.getText().trim();
        String noHp = jTextField5.getText().trim();
        String address = txtAddress.getText().trim();

        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama harus diisi!");
            return;
        }
        if (!rbLakiLaki.isSelected() && !rbPerempuan.isSelected()) {
            JOptionPane.showMessageDialog(this, "Jenis Kelamin harus dipilih!");
            return;
        }
        selectedGender = rbLakiLaki.isSelected() ? "L" : "P";

        try {
            String query = "INSERT INTO m_customer (customer_name, phone_number, gender, address) VALUES (?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(query, Statement.RETURN_GENERATED_KEYS);
            pstmt.setString(1, nama);
            pstmt.setString(2, noHp.isEmpty() ? null : noHp);
            pstmt.setString(3, selectedGender);
            pstmt.setString(4, address.isEmpty() ? null : address);
            pstmt.executeUpdate();

            ResultSet rs = pstmt.getGeneratedKeys();
            if (rs.next()) {
                selectedCustomerId = rs.getInt(1);
            }
            JOptionPane.showMessageDialog(this, "Customer berhasil ditambahkan!");
            loadCustomers();
            jComboBox1.setSelectedItem(selectedCustomerId + " - " + nama);
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error menambah customer: " + e.getMessage());
        }
    }

    private void setupTable() {
        DefaultTableModel model = new DefaultTableModel(
                new Object[]{"ID Produk", "Kode Produk", "Nama Produk", "Harga", "Jumlah", "Subtotal", "Aksi"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return column == COL_JUMLAH || column == COL_AKSI;
            }

            @Override
            public void setValueAt(Object aValue, int row, int column) {
                // Validasi khusus untuk kolom Jumlah
                if (column == COL_JUMLAH) {
                    try {
                        int qtyBaru = Integer.parseInt(aValue.toString());
                        if (qtyBaru <= 0) {
                            JOptionPane.showMessageDialog(FormPenjualan.this,
                                    "Jumlah harus lebih dari 0!", "Error", JOptionPane.ERROR_MESSAGE);
                            return; // batal set nilai
                        }

                        // Ambil ID produk dan stok terkini
                        int productId = (int) getValueAt(row, COL_ID_PRODUK);
                        int stok = getStock(productId); // tangani SQLException di sini

                        if (qtyBaru > stok) {
                            JOptionPane.showMessageDialog(FormPenjualan.this,
                                    "Stok tidak mencukupi!\nStok tersedia: " + stok,
                                    "Stok Tidak Cukup", JOptionPane.WARNING_MESSAGE);
                            return; // batal set nilai
                        }
                    } catch (NumberFormatException ex) {
                        JOptionPane.showMessageDialog(FormPenjualan.this,
                                "Masukkan angka yang valid!", "Error", JOptionPane.ERROR_MESSAGE);
                        return;
                    } catch (SQLException ex) {
                        JOptionPane.showMessageDialog(FormPenjualan.this,
                                "Gagal memeriksa stok: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
                // Jika validasi lolos, set nilai sebenarnya
                super.setValueAt(aValue, row, column);
            }
        };

        jTable1.setModel(model);

        // Sembunyikan kolom ID Produk
        jTable1.getColumnModel().getColumn(COL_ID_PRODUK).setMinWidth(0);
        jTable1.getColumnModel().getColumn(COL_ID_PRODUK).setMaxWidth(0);
        jTable1.getColumnModel().getColumn(COL_ID_PRODUK).setPreferredWidth(0);

        jTable1.getColumnModel().getColumn(COL_KODE_PRODUK).setPreferredWidth(80);
        jTable1.getColumnModel().getColumn(COL_NAMA_PRODUK).setPreferredWidth(150);
        jTable1.getColumnModel().getColumn(COL_HARGA).setPreferredWidth(100);
        jTable1.getColumnModel().getColumn(COL_JUMLAH).setPreferredWidth(70);
        jTable1.getColumnModel().getColumn(COL_SUBTOTAL).setPreferredWidth(100);
        jTable1.getColumnModel().getColumn(COL_AKSI).setPreferredWidth(80);

        // Renderer format Rupiah
        TableCellRenderer rupiahRenderer = (table, value, isSelected, hasFocus, row, column) -> {
            JLabel label = new JLabel();
            if (value instanceof Number) {
                label.setText(String.format("Rp %,.2f", ((Number) value).doubleValue()));
            } else {
                label.setText(value != null ? value.toString() : "");
            }
            label.setOpaque(true);
            if (isSelected) {
                label.setBackground(table.getSelectionBackground());
                label.setForeground(table.getSelectionForeground());
            } else {
                label.setBackground(table.getBackground());
                label.setForeground(table.getForeground());
            }
            label.setBorder(BorderFactory.createEmptyBorder(0, 5, 0, 5));
            return label;
        };
        jTable1.getColumnModel().getColumn(COL_HARGA).setCellRenderer(rupiahRenderer);
        jTable1.getColumnModel().getColumn(COL_SUBTOTAL).setCellRenderer(rupiahRenderer);

        // Renderer tombol Hapus
        jTable1.getColumn("Aksi").setCellRenderer((table, value, isSelected, hasFocus, row, column) -> {
            JButton btnHapus = new JButton("Hapus");
            btnHapus.setFocusPainted(false);
            return btnHapus;
        });

        // Editor tombol Hapus
        jTable1.getColumn("Aksi").setCellEditor(new DefaultCellEditor(new JCheckBox()) {
            private JButton button;
            private int currentRow;

            {
                button = new JButton("Hapus");
                button.setFocusPainted(false);
                button.addActionListener(e -> {
                    fireEditingStopped();
                    hapusProdukDariTable(currentRow);
                });
            }

            @Override
            public Component getTableCellEditorComponent(JTable table, Object value,
                    boolean isSelected, int row, int column) {
                currentRow = row;
                return button;
            }

            @Override
            public Object getCellEditorValue() {
                return "Hapus";
            }
        });

        // Listener untuk update subtotal & grand total
        model.addTableModelListener(e -> {
            if (e.getColumn() == COL_JUMLAH) {
                int row = e.getFirstRow();
                updateRowSubtotal(row);
                hitungGrandTotal();
            }
        });
    }

    private void hapusProdukDariTable(int row) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        if (row >= 0 && row < model.getRowCount()) {
            model.removeRow(row);
            hitungGrandTotal();
        }
    }

    private void updateRowSubtotal(int row) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        if (row >= 0 && row < model.getRowCount()) {
            double harga = (double) model.getValueAt(row, COL_HARGA);
            int jumlah = Integer.parseInt(model.getValueAt(row, COL_JUMLAH).toString());
            double subtotal = harga * jumlah;
            model.setValueAt(subtotal, row, COL_SUBTOTAL);
        }
    }

    private void hitungGrandTotal() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        double total = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            total += (double) model.getValueAt(i, COL_SUBTOTAL);
        }
        jTextField3.setText(String.format("Rp %.2f", total));
    }

