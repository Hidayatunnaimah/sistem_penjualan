    private void onPelangganSelected() {
        String selected = (String) jComboBox1.getSelectedItem();
        if (selected == null || selected.equals("-- Pilih Pelanggan --")) {
            jTextField4.setText("");
            jTextField5.setText("");
            jTextField4.setEditable(false);
            jTextField5.setEditable(false);
            removeAddButton();
            hideGuestFields();
            selectedCustomerId = 0;
            return;
        }

        if (selected.equals("GUEST")) {
            jTextField4.setText("");
            jTextField5.setText("");
            jTextField4.setEditable(true);
            jTextField5.setEditable(true);
            txtAddress.setText("");
            bgJenisKelamin.clearSelection();
            selectedCustomerId = 0;
            showGuestFields();
            addCustomerButton();
        } else {
            try {
                String[] parts = selected.split(" - ");
                int customerId = Integer.parseInt(parts[0]);
                selectedCustomerId = customerId;

                String query = "SELECT * FROM m_customer WHERE id = ?";
                PreparedStatement pstmt = conn.prepareStatement(query);
                pstmt.setInt(1, customerId);
                ResultSet rs = pstmt.executeQuery();
                if (rs.next()) {
                    jTextField4.setText(rs.getString("customer_name"));
                    jTextField5.setText(rs.getString("phone_number"));
                    jTextField4.setEditable(false);
                    jTextField5.setEditable(false);
                }
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
            removeAddButton();
            hideGuestFields();
        }
    }

