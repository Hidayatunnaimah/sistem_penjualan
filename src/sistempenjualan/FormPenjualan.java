    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed

        JDialog dialog = new JDialog((Frame) SwingUtilities.getWindowAncestor(this), "Pilih Produk", true);
        dialog.setSize(550, 400);
        dialog.setLocationRelativeTo(this);

        JPanel panel = new JPanel(new BorderLayout(10, 10));
        panel.setBorder(BorderFactory.createEmptyBorder(10, 10, 10, 10));

        // Model tabel: ID, Kode, Nama Produk, Harga, Stok
        DefaultTableModel modelProduk = new DefaultTableModel(
                new Object[]{"ID", "Kode", "Nama Produk", "Harga", "Stok"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        JTable tblProduk = new JTable(modelProduk);

        // Sembunyikan kolom ID
        tblProduk.getColumnModel().getColumn(0).setMinWidth(0);
        tblProduk.getColumnModel().getColumn(0).setMaxWidth(0);
        tblProduk.getColumnModel().getColumn(0).setPreferredWidth(0);
        // Lebar kolom lain
        tblProduk.getColumnModel().getColumn(1).setPreferredWidth(80);
        tblProduk.getColumnModel().getColumn(2).setPreferredWidth(180);
        tblProduk.getColumnModel().getColumn(3).setPreferredWidth(100);
        tblProduk.getColumnModel().getColumn(4).setPreferredWidth(60);

        JScrollPane scroll = new JScrollPane(tblProduk);

        // Load produk dengan stok dari database
        Map<Integer, Integer> stockMap = new HashMap<>();
        try {
            String query = "SELECT p.id, p.code, p.product_name, p.price, COALESCE(s.stock, 0) AS stock "
                    + "FROM m_product p LEFT JOIN stock s ON p.id = s.product_id ORDER BY p.product_name";
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(query);

            while (rs.next()) {
                int id = rs.getInt("id");
                int stock = rs.getInt("stock");
                modelProduk.addRow(new Object[]{
                    id,
                    rs.getString("code"),
                    rs.getString("product_name"),
                    rs.getDouble("price"),
                    stock
                });
                stockMap.put(id, stock);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error loading produk: " + e.getMessage());
        }

        JButton btnPilih = new JButton("Pilih");
        btnPilih.setEnabled(false); // akan diaktifkan setelah ada baris terpilih dengan stok > 0

        // Listener untuk mengaktifkan tombol hanya jika baris dipilih dan stok > 0
        tblProduk.getSelectionModel().addListSelectionListener(e -> {
            int selectedRow = tblProduk.getSelectedRow();
            if (selectedRow >= 0) {
                int stok = (int) modelProduk.getValueAt(selectedRow, 4);
                btnPilih.setEnabled(stok > 0);
            } else {
                btnPilih.setEnabled(false);
            }
        });

        btnPilih.addActionListener(e -> {
            int selectedRow = tblProduk.getSelectedRow();
            if (selectedRow >= 0) {
                int id = (int) modelProduk.getValueAt(selectedRow, 0);
                String kode = (String) modelProduk.getValueAt(selectedRow, 1);
                String nama = (String) modelProduk.getValueAt(selectedRow, 2);
                double harga = (double) modelProduk.getValueAt(selectedRow, 3);
                int stok = (int) modelProduk.getValueAt(selectedRow, 4);

                // Periksa stok (seharusnya sudah >0 karena tombol hanya aktif jika stok>0)
                if (stok <= 0) {
                    JOptionPane.showMessageDialog(dialog, "Stok produk ini habis!", "Stok Habis", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                // Tambahkan ke tabel transaksi (qty default 1)
                DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

                boolean produkSudahAda = false;
                for (int i = 0; i < model.getRowCount(); i++) {
                    int idDiTable = (int) model.getValueAt(i, COL_ID_PRODUK);
                    if (idDiTable == id) {
                        int qtyLama = Integer.parseInt(model.getValueAt(i, COL_JUMLAH).toString());
                        int qtyBaru = qtyLama + 1;

                        // Cek apakah melebihi stok
                        if (qtyBaru > stok) {
                            JOptionPane.showMessageDialog(dialog,
                                    "Stok tidak mencukupi! Stok tersedia: " + stok,
                                    "Stok Tidak Cukup", JOptionPane.WARNING_MESSAGE);
                            return;
                        }

                        model.setValueAt(qtyBaru, i, COL_JUMLAH);
                        double subtotalBaru = harga * qtyBaru;
                        model.setValueAt(subtotalBaru, i, COL_SUBTOTAL);
                        produkSudahAda = true;
                        break;
                    }
                }

                if (!produkSudahAda) {
                    model.addRow(new Object[]{
                        id, kode, nama, harga, 1, harga, "Hapus"
                    });
                }

                hitungGrandTotal();
                dialog.dispose();
            } else {
                JOptionPane.showMessageDialog(dialog, "Pilih produk terlebih dahulu!");
            }
        });

        panel.add(scroll, BorderLayout.CENTER);
        panel.add(btnPilih, BorderLayout.SOUTH);

        dialog.add(panel);
        dialog.setVisible(true);

    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        if (selectedCustomerId == 0 && !jComboBox1.getSelectedItem().equals("GUEST")) {
            JOptionPane.showMessageDialog(this, "Pilih pelanggan terlebih dahulu!");
            return;
        }

        if (jTable1.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Tambahkan produk terlebih dahulu!");
            return;
        }

        try {
            conn.setAutoCommit(false);

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            double grandTotal = 0;

            // Validasi stok untuk setiap item
            for (int i = 0; i < model.getRowCount(); i++) {
                int productId = (int) model.getValueAt(i, COL_ID_PRODUK);
                int qty = Integer.parseInt(model.getValueAt(i, COL_JUMLAH).toString());
                int stok = getStock(productId);

                if (qty > stok) {
                    conn.rollback();
                    JOptionPane.showMessageDialog(this,
                            "Stok tidak mencukupi untuk produk: " + model.getValueAt(i, COL_NAMA_PRODUK)
                            + "\nStok tersedia: " + stok + ", diminta: " + qty,
                            "Stok Tidak Cukup", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            // Insert transaksi header
            String queryTransaksi = "INSERT INTO trx (trx_number, created_at, sales_id, customer_id, grand_total) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pstmtTransaksi = conn.prepareStatement(queryTransaksi, Statement.RETURN_GENERATED_KEYS);
            pstmtTransaksi.setString(1, jTextField1.getText());
            pstmtTransaksi.setString(2, jTextField2.getText());
            pstmtTransaksi.setInt(3, this.app.getSessionUserId());
            pstmtTransaksi.setInt(4, selectedCustomerId);

            // Hitung grand total ulang dengan aman
            for (int i = 0; i < model.getRowCount(); i++) {
                Object subtotalObj = model.getValueAt(i, COL_SUBTOTAL);
                if (subtotalObj instanceof Number) {
                    grandTotal += ((Number) subtotalObj).doubleValue();
                }
            }
            pstmtTransaksi.setDouble(5, grandTotal);
            pstmtTransaksi.executeUpdate();

            ResultSet rs = pstmtTransaksi.getGeneratedKeys();
            int idTransaksi = 0;
            if (rs.next()) {
                idTransaksi = rs.getInt(1);
            }

            // Insert detail transaksi dan update stok
            String queryDetail = "INSERT INTO trx_detail (trx_id, product_id, qty, subprice, price) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pstmtDetail = conn.prepareStatement(queryDetail);
            String updateStok = "UPDATE stock SET stock = stock - ? WHERE product_id = ?";

            for (int i = 0; i < model.getRowCount(); i++) {
                int productId = (int) model.getValueAt(i, COL_ID_PRODUK);
                int qty = Integer.parseInt(model.getValueAt(i, COL_JUMLAH).toString());

                Object hargaObj = model.getValueAt(i, COL_HARGA);
                Object subtotalObj = model.getValueAt(i, COL_SUBTOTAL);
                double harga = hargaObj instanceof Number ? ((Number) hargaObj).doubleValue() : 0;
                double subtotal = subtotalObj instanceof Number ? ((Number) subtotalObj).doubleValue() : 0;

                pstmtDetail.setInt(1, idTransaksi);
                pstmtDetail.setInt(2, productId);
                pstmtDetail.setInt(3, qty);
                pstmtDetail.setDouble(4, harga);      // subprice = harga satuan
                pstmtDetail.setDouble(5, subtotal);   // price = total harga (qty * harga)
                pstmtDetail.executeUpdate();

                // Update stok
                PreparedStatement pstmtStok = conn.prepareStatement(updateStok);
                pstmtStok.setInt(1, qty);
                pstmtStok.setInt(2, productId);
                pstmtStok.executeUpdate();
            }

            conn.commit();
            tampilkanRincianTransaksi(idTransaksi, jTextField1.getText(), grandTotal);

            // Reset form
            resetForm();

        } catch (SQLException e) {
            try {
                conn.rollback();
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
            JOptionPane.showMessageDialog(this, "Error menyimpan transaksi: " + e.getMessage());
            e.printStackTrace();
        } finally {
            try {
                conn.setAutoCommit(true);
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton3ActionPerformed

    private int getStock(int productId) throws SQLException {
        String sql = "SELECT COALESCE(stock, 0) AS stock FROM stock WHERE product_id = ?";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, productId);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                return rs.getInt("stock");
            }
        }
        return 0;
    }

